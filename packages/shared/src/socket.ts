import { z } from 'zod';
import { colorModeSchema, idSchema, kioskStatusSchema, paperLevelSchema } from './schemas';

/** Last 3 digits of a pickup code, shown on the shared kiosk screen. */
export function pickupCodeHint(pickupCode: string | null): string {
  return pickupCode ? `•••${pickupCode.slice(-3)}` : '•••';
}

/** Socket.IO namespaces. */
export const SocketNamespace = {
  /** Print agents running on the kiosk PCs (outbound connection from the agent). */
  AGENTS: '/agents',
  /** Customer phones, one room per job id. */
  CLIENTS: '/clients',
  /** Kiosk screens. */
  KIOSKS: '/kiosks',
} as const;

/**
 * Agent ↔ server events. The payload schemas below are the single source of truth for each
 * contract; both sides validate what they receive.
 *
 * Reliability: every agent → server event except the heartbeat goes through the agent's
 * persistent outbox and is retried until acknowledged, so server handlers are idempotent.
 */
export const AgentEvent = {
  // agent → server
  /** Sent after each (re)connection, once the outbox is flushed. The server then resends work. */
  READY: 'agent:ready',
  HEARTBEAT: 'agent:heartbeat',
  JOB_ACK: 'job:ack',
  JOB_PRINTING: 'job:printing',
  JOB_PRINTED: 'job:printed',
  JOB_FAILED: 'job:failed',
  COIN_INSERTED: 'coin:inserted',
  COIN_DISPENSED: 'coin:dispensed',
  /** The hopper could not pay everything back (empty, jammed). */
  COIN_SHORTFALL: 'coin:shortfall',
  // server → agent
  JOB_DISPATCH: 'job:dispatch',
  /** Enable/disable the coin validator and show the amount due. */
  COIN_ACCEPT: 'coin:accept',
  /** Pay money back with the hopper (change or refund). */
  COIN_DISPENSE: 'coin:dispense',
} as const;

/** Customer phone ↔ server (`/clients` namespace). */
export const ClientEvent = {
  /** Phone → server, with ack: follow a job of this session (room per job id). */
  SUBSCRIBE: 'job:subscribe',
  /** Server → phone: the job changed; payload is the full `JobView`. */
  JOB_STATUS: 'job:status',
} as const;

/** Socket.IO handshake `auth` of the customer phone. */
export const clientAuthSchema = z.object({
  sessionToken: z.string().min(10).max(4096),
});

export const jobSubscribeSchema = z.object({ jobId: idSchema });

export const KioskEvent = {
  STATE: 'kiosk:state',
} as const;

/** Socket.IO handshake `auth` of the agent. */
export const agentAuthSchema = z.object({
  kioskId: idSchema,
  apiKey: z.string().min(10).max(200),
});
export type AgentAuth = z.infer<typeof agentAuthSchema>;

/** Every acknowledgement callback receives this. */
export const agentAckSchema = z.object({
  ok: z.boolean(),
  error: z.string().optional(),
});
export type AgentAck = z.infer<typeof agentAckSchema>;

export const agentHeartbeatSchema = z.object({
  agentVersion: z.string().max(32),
  printer: z.object({
    name: z.string().max(200),
    online: z.boolean(),
    /** Windows printer status name (Get-Printer PrinterStatus), e.g. "Normal", "PaperOut". */
    status: z.string().max(100),
    queuedJobs: z.number().int().nonnegative(),
    paperLevel: paperLevelSchema,
  }),
  coinDevice: z
    .object({
      connected: z.boolean(),
      /** Hopper reports it is nearly out of coins: change may fall short soon. */
      hopperLow: z.boolean(),
    })
    .nullable(),
  diskFreeBytes: z.number().int().nonnegative(),
  /** Jobs waiting in the agent's local queue. */
  localQueue: z.number().int().nonnegative(),
});
export type AgentHeartbeat = z.infer<typeof agentHeartbeatSchema>;

/** Server → agent: a paid job to print. May be sent several times: the agent deduplicates. */
export const jobDispatchSchema = z.object({
  jobId: idSchema,
  /** Pre-signed URL, valid ~2 min. */
  downloadUrl: z.url(),
  copies: z.number().int().positive(),
  colorMode: colorModeSchema,
  duplex: z.boolean(),
  /** SumatraPDF page selection, e.g. `"1-3,5"`; `null` = all pages. */
  pageRange: z.string().nullable(),
});
export type JobDispatch = z.infer<typeof jobDispatchSchema>;

export const jobRefSchema = z.object({ jobId: idSchema });
export type JobRef = z.infer<typeof jobRefSchema>;

export const JobFailureReason = {
  DOWNLOAD_FAILED: 'DOWNLOAD_FAILED',
  PRINTER_ERROR: 'PRINTER_ERROR',
  PRINT_TIMEOUT: 'PRINT_TIMEOUT',
  /** The agent stopped while printing this job: not reprinted automatically (no double print). */
  INTERRUPTED: 'INTERRUPTED',
  INVALID_JOB: 'INVALID_JOB',
} as const;
export type JobFailureReason = (typeof JobFailureReason)[keyof typeof JobFailureReason];

export const jobFailedSchema = z.object({
  jobId: idSchema,
  reason: z.enum(JobFailureReason),
  /** Technical detail for the operator (no file content or name). */
  detail: z.string().max(500).optional(),
});
export type JobFailed = z.infer<typeof jobFailedSchema>;

/** One coin accepted by the validator. `eventId` is generated by the agent (idempotence). */
export const coinInsertedSchema = z.object({
  eventId: z.uuid(),
  valueMillimes: z.number().int().positive().max(100_000),
});
export type CoinInserted = z.infer<typeof coinInsertedSchema>;

/** Server → agent: enable the validator while a customer pays, disable it otherwise. */
export const coinAcceptSchema = z.object({
  enabled: z.boolean(),
  jobId: idSchema.nullable(),
  amountDueMillimes: z.number().int().nonnegative(),
  receivedMillimes: z.number().int().nonnegative(),
});
export type CoinAccept = z.infer<typeof coinAcceptSchema>;

/**
 * Server → agent: pay `amountMillimes` back. `commandId` changes with the amount still owed, so
 * the agent executes each command once even when the server resends it after a reconnection.
 */
export const coinDispenseSchema = z.object({
  commandId: z.string().min(1).max(200),
  paymentId: idSchema.nullable(),
  amountMillimes: z.number().int().positive().max(1_000_000),
});
export type CoinDispense = z.infer<typeof coinDispenseSchema>;

export const coinDispensedSchema = z.object({
  eventId: z.uuid(),
  commandId: z.string().min(1).max(200),
  paymentId: idSchema.nullable(),
  valueMillimes: z.number().int().positive().max(100_000),
});
export type CoinDispensed = z.infer<typeof coinDispensedSchema>;

export const coinShortfallSchema = z.object({
  commandId: z.string().min(1).max(200),
  paymentId: idSchema.nullable(),
  missingMillimes: z.number().int().positive(),
});
export type CoinShortfall = z.infer<typeof coinShortfallSchema>;

// --- Kiosk screen ------------------------------------------------------------------------------

/** Socket.IO handshake `auth` of the kiosk screen (display key, not the agent key). */
export const kioskScreenAuthSchema = z.object({
  kioskId: idSchema,
  displayKey: z.string().min(10).max(200),
});
export type KioskScreenAuth = z.infer<typeof kioskScreenAuthSchema>;

export const OutOfServiceReason = {
  /** The print agent is not connected (PC off, network down, service stopped). */
  AGENT_OFFLINE: 'AGENT_OFFLINE',
  /** Printer or coin machine in error (paper out, jam, offline…). */
  DEVICE_ERROR: 'DEVICE_ERROR',
} as const;
export type OutOfServiceReason = (typeof OutOfServiceReason)[keyof typeof OutOfServiceReason];

/**
 * Server → kiosk screen (`kiosk:state`, also `GET /api/kiosks/:id/screen`). Pushed again on
 * every change: job status, coin payment, agent connection, printer state.
 */
export const kioskScreenStateSchema = z.object({
  kioskId: idSchema,
  name: z.string(),
  status: kioskStatusSchema,
  /** Null when the kiosk can print; otherwise the screen shows "Hors service". */
  outOfService: z.enum(OutOfServiceReason).nullable(),
  paperLevel: paperLevelSchema,
  /** Paid jobs waiting or printing, oldest first. */
  queue: z.array(
    z.object({
      /** Last 3 digits of the pickup code, so customers recognise their job (`•••731`). */
      codeHint: z.string(),
      status: z.enum(['PAID', 'QUEUED', 'PRINTING']),
      pages: z.number().int().nonnegative(),
    }),
  ),
  /** Customer currently paying at the coin machine. */
  coinPayment: z
    .object({
      codeHint: z.string(),
      amountDueMillimes: z.number().int().nonnegative(),
      receivedMillimes: z.number().int().nonnegative(),
      expiresAt: z.iso.datetime(),
    })
    .nullable(),
  updatedAt: z.iso.datetime(),
});
export type KioskScreenState = z.infer<typeof kioskScreenStateSchema>;
