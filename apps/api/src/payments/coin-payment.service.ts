import { Injectable, Logger } from '@nestjs/common';
import { EventEmitter2 } from '@nestjs/event-emitter';
import { CoinEventKind, JobStatus, Payment, PaymentProvider, PaymentStatus } from '@prisma/client';
import { ApiErrorCode, CoinSessionView, TIMINGS } from '@printbox/shared';
import { ApiException, notFound } from '../common/api-exception';
import { PrintSessionContext } from '../common/request-context';
import {
  CoinChangeDueEvent,
  CoinSessionUpdatedEvent,
  DomainEvent,
  JobStatusChangedEvent,
} from '../events/domain-events';
import { invalidJobState, PrismaTx } from '../jobs/job-state.service';
import { PrismaService } from '../prisma/prisma.service';
import { PaymentProviders } from './payment-providers';
import { PaymentsService } from './payments.service';

/** One coin reported by the kiosk agent. `eventId` is generated by the agent (idempotence). */
export interface CoinReport {
  eventId: string;
  valueMillimes: number;
}

export type CoinInsertedOutcome =
  /** Already recorded: the agent re-sent it (reconnection). Nothing changes. */
  | { kind: 'duplicate' }
  /** Nobody is paying: the coin must be given back. */
  | { kind: 'orphan'; refundMillimes: number }
  | { kind: 'partial'; jobId: string; receivedMillimes: number; amountDueMillimes: number }
  | { kind: 'paid'; jobId: string; changeDueMillimes: number };

const kioskBusy = (): ApiException =>
  new ApiException(
    409,
    ApiErrorCode.KIOSK_BUSY,
    'Un autre client paie à la borne, réessayez dans un instant',
  );

/** Serialises everything touching one kiosk's coin machine (row lock until commit). */
async function lockKiosk(tx: PrismaTx, kioskId: string): Promise<void> {
  await tx.$queryRaw`SELECT id FROM "Kiosk" WHERE id = ${kioskId} FOR UPDATE`;
}

function latestPendingCoinPayment(tx: PrismaTx, jobId: string): Promise<Payment | null> {
  return tx.payment.findFirst({
    where: { jobId, provider: PaymentProvider.COIN, status: PaymentStatus.PENDING },
    orderBy: { createdAt: 'desc' },
  });
}

/**
 * Coin machine payments. One customer at a time per kiosk: the job holds a reservation
 * (`Kiosk.paymentJobId`) for 3 minutes, extended by each coin. When the coins cover the price
 * the job is PAID and any surplus becomes change due; an abandoned or lapsed reservation
 * makes every inserted coin a refund. The agent pays both back with the hopper.
 */
@Injectable()
export class CoinPaymentService {
  private readonly logger = new Logger(CoinPaymentService.name);

  constructor(
    private readonly prisma: PrismaService,
    private readonly providers: PaymentProviders,
    private readonly payments: PaymentsService,
    private readonly events: EventEmitter2,
  ) {}

  /** Reserves the kiosk coin machine for this job (or refreshes the reservation it holds). */
  async start(
    session: PrintSessionContext,
    jobId: string,
    now = new Date(),
  ): Promise<CoinSessionView> {
    const job = await this.prisma.printJob.findFirst({
      where: { id: jobId, sessionId: session.id },
      select: { id: true, kioskId: true, status: true, priceMillimes: true },
    });
    if (!job) throw notFound();
    if (job.status !== JobStatus.AWAITING_PAYMENT || job.priceMillimes === null) {
      throw invalidJobState();
    }
    const amountMillimes = job.priceMillimes;

    await this.settleIfLapsed(job.kioskId, now);

    const expiresAt = new Date(now.getTime() + TIMINGS.coinPaymentWindowMs);
    const payment = await this.prisma.$transaction(async (tx) => {
      await lockKiosk(tx, job.kioskId);
      const kiosk = await tx.kiosk.findUniqueOrThrow({
        where: { id: job.kioskId },
        select: { paymentJobId: true },
      });
      if (kiosk.paymentJobId !== null && kiosk.paymentJobId !== job.id) throw kioskBusy();
      await tx.kiosk.update({
        where: { id: job.kioskId },
        data: { paymentJobId: job.id, paymentExpiresAt: expiresAt },
      });
      return (
        (await latestPendingCoinPayment(tx, job.id)) ??
        this.providers
          .get(PaymentProvider.COIN)
          .createPayment(tx, { jobId: job.id, amountMillimes })
      );
    });

    this.emitSession({
      kioskId: job.kioskId,
      jobId: job.id,
      active: true,
      amountDueMillimes: payment.amountMillimes,
      receivedMillimes: payment.receivedMillimes,
      expiresAt,
    });
    return this.view(job.id, JobStatus.AWAITING_PAYMENT, payment, expiresAt);
  }

  /** Current reservation of this job, or 404 when it holds none. */
  async get(session: PrintSessionContext, jobId: string): Promise<CoinSessionView> {
    const job = await this.prisma.printJob.findFirst({
      where: { id: jobId, sessionId: session.id },
      select: {
        id: true,
        status: true,
        kiosk: { select: { paymentJobId: true, paymentExpiresAt: true } },
      },
    });
    if (!job || job.kiosk.paymentJobId !== job.id || !job.kiosk.paymentExpiresAt) throw notFound();
    const payment = await latestPendingCoinPayment(this.prisma, job.id);
    if (!payment) throw notFound();
    return this.view(job.id, job.status, payment, job.kiosk.paymentExpiresAt);
  }

  /** The customer gives up paying with coins: coins already inserted are given back. */
  async cancel(session: PrintSessionContext, jobId: string): Promise<void> {
    const job = await this.prisma.printJob.findFirst({
      where: { id: jobId, sessionId: session.id },
      select: { id: true },
    });
    if (!job) throw notFound();
    await this.releaseForJob(job.id);
  }

  /** Ends the reservation this job may hold (job cancelled, paid at the counter…). */
  async releaseForJob(jobId: string): Promise<void> {
    const kiosk = await this.prisma.kiosk.findUnique({
      where: { paymentJobId: jobId },
      select: { id: true },
    });
    if (kiosk) await this.settle(kiosk.id, jobId);
  }

  /** Called by the agent for each accepted coin. */
  async recordInserted(
    kioskId: string,
    coin: CoinReport,
    now = new Date(),
  ): Promise<CoinInsertedOutcome> {
    if (!Number.isSafeInteger(coin.valueMillimes) || coin.valueMillimes <= 0) {
      throw new RangeError('Coin value must be a positive integer of millimes');
    }

    const outcome = await this.prisma.$transaction(async (tx) => {
      await lockKiosk(tx, kioskId);
      if (await tx.coinEvent.findUnique({ where: { id: coin.eventId }, select: { id: true } })) {
        return { kind: 'duplicate' as const };
      }
      const kiosk = await tx.kiosk.findUniqueOrThrow({
        where: { id: kioskId },
        select: { paymentJobId: true, paymentExpiresAt: true },
      });
      const reserved =
        kiosk.paymentJobId !== null &&
        kiosk.paymentExpiresAt !== null &&
        kiosk.paymentExpiresAt > now;
      const payment = reserved ? await latestPendingCoinPayment(tx, kiosk.paymentJobId!) : null;

      await tx.coinEvent.create({
        data: {
          id: coin.eventId,
          kioskId,
          kind: CoinEventKind.INSERTED,
          valueMillimes: coin.valueMillimes,
          paymentId: payment?.id ?? null,
        },
      });
      if (!payment) return { kind: 'orphan' as const, refundMillimes: coin.valueMillimes };

      const updated = await tx.payment.update({
        where: { id: payment.id },
        data: { receivedMillimes: { increment: coin.valueMillimes } },
      });
      if (updated.receivedMillimes < updated.amountMillimes) {
        const expiresAt = new Date(now.getTime() + TIMINGS.coinPaymentWindowMs);
        await tx.kiosk.update({ where: { id: kioskId }, data: { paymentExpiresAt: expiresAt } });
        return { kind: 'partial' as const, payment: updated, expiresAt };
      }

      const changeDueMillimes = updated.receivedMillimes - updated.amountMillimes;
      await tx.payment.update({ where: { id: payment.id }, data: { changeDueMillimes } });
      await this.payments.completePayment(tx, {
        jobId: payment.jobId,
        paymentId: payment.id,
        provider: PaymentProvider.COIN,
        actor: `agent:${kioskId}`,
      });
      await tx.kiosk.update({
        where: { id: kioskId },
        data: { paymentJobId: null, paymentExpiresAt: null },
      });
      return { kind: 'paid' as const, payment: { ...updated, changeDueMillimes } };
    });

    switch (outcome.kind) {
      case 'duplicate':
        return outcome;
      case 'orphan':
        this.logger.warn(
          { kioskId, valueMillimes: coin.valueMillimes },
          'Coin inserted with no payment in progress',
        );
        this.emitChangeDue({
          kioskId,
          paymentId: null,
          amountMillimes: coin.valueMillimes,
          reason: 'REFUND',
        });
        return outcome;
      case 'partial':
        this.emitSession({
          kioskId,
          jobId: outcome.payment.jobId,
          active: true,
          amountDueMillimes: outcome.payment.amountMillimes,
          receivedMillimes: outcome.payment.receivedMillimes,
          expiresAt: outcome.expiresAt,
        });
        return {
          kind: 'partial',
          jobId: outcome.payment.jobId,
          receivedMillimes: outcome.payment.receivedMillimes,
          amountDueMillimes: outcome.payment.amountMillimes,
        };
      case 'paid': {
        const { payment } = outcome;
        this.emitSession({
          kioskId,
          jobId: payment.jobId,
          active: false,
          amountDueMillimes: payment.amountMillimes,
          receivedMillimes: payment.receivedMillimes,
          expiresAt: null,
        });
        this.events.emit(DomainEvent.JOB_STATUS_CHANGED, {
          jobId: payment.jobId,
          kioskId,
          status: JobStatus.PAID,
        } satisfies JobStatusChangedEvent);
        if (payment.changeDueMillimes > 0) {
          this.emitChangeDue({
            kioskId,
            paymentId: payment.id,
            amountMillimes: payment.changeDueMillimes,
            reason: 'CHANGE',
          });
        }
        return { kind: 'paid', jobId: payment.jobId, changeDueMillimes: payment.changeDueMillimes };
      }
    }
  }

  /** Called by the agent for each coin the hopper paid back. Idempotent like `recordInserted`. */
  async recordDispensed(
    kioskId: string,
    coin: CoinReport & { paymentId: string | null },
  ): Promise<void> {
    await this.prisma.$transaction(async (tx) => {
      await lockKiosk(tx, kioskId);
      if (await tx.coinEvent.findUnique({ where: { id: coin.eventId }, select: { id: true } }))
        return;
      const payment = coin.paymentId
        ? await tx.payment.findFirst({
            where: { id: coin.paymentId, job: { kioskId } },
            select: { id: true },
          })
        : null;
      await tx.coinEvent.create({
        data: {
          id: coin.eventId,
          kioskId,
          kind: CoinEventKind.DISPENSED,
          valueMillimes: coin.valueMillimes,
          paymentId: payment?.id ?? null,
        },
      });
      if (payment) {
        await tx.payment.update({
          where: { id: payment.id },
          data: { changeDispensedMillimes: { increment: coin.valueMillimes } },
        });
      }
    });
  }

  /** Ends every reservation that ran out of time. Run periodically. */
  async expireLapsed(now = new Date()): Promise<number> {
    const lapsed = await this.prisma.kiosk.findMany({
      where: { paymentJobId: { not: null }, paymentExpiresAt: { lte: now } },
      select: { id: true, paymentJobId: true },
    });
    for (const kiosk of lapsed) {
      await this.settle(kiosk.id, kiosk.paymentJobId!, now);
    }
    return lapsed.length;
  }

  private async settleIfLapsed(kioskId: string, now: Date): Promise<void> {
    const kiosk = await this.prisma.kiosk.findUniqueOrThrow({
      where: { id: kioskId },
      select: { paymentJobId: true, paymentExpiresAt: true },
    });
    if (kiosk.paymentJobId && kiosk.paymentExpiresAt && kiosk.paymentExpiresAt <= now) {
      await this.settle(kioskId, kiosk.paymentJobId, now);
    }
  }

  /**
   * Ends the reservation of `jobId` on this kiosk without payment: the pending coin payment is
   * CANCELLED and every coin received becomes a refund. With `lapsedAt`, only if it has lapsed.
   */
  private async settle(kioskId: string, jobId: string, lapsedAt?: Date): Promise<void> {
    const settled = await this.prisma.$transaction(async (tx) => {
      await lockKiosk(tx, kioskId);
      const kiosk = await tx.kiosk.findUniqueOrThrow({
        where: { id: kioskId },
        select: { paymentJobId: true, paymentExpiresAt: true },
      });
      if (kiosk.paymentJobId !== jobId) return null;
      if (lapsedAt && kiosk.paymentExpiresAt && kiosk.paymentExpiresAt > lapsedAt) return null;

      const payment = await latestPendingCoinPayment(tx, jobId);
      const cancelled = payment
        ? await tx.payment.update({
            where: { id: payment.id },
            data: { status: PaymentStatus.CANCELLED, changeDueMillimes: payment.receivedMillimes },
          })
        : null;
      await tx.kiosk.update({
        where: { id: kioskId },
        data: { paymentJobId: null, paymentExpiresAt: null },
      });
      return { payment: cancelled };
    });
    if (!settled) return;

    const payment = settled.payment;
    this.emitSession({
      kioskId,
      jobId,
      active: false,
      amountDueMillimes: payment?.amountMillimes ?? 0,
      receivedMillimes: payment?.receivedMillimes ?? 0,
      expiresAt: null,
    });
    if (payment && payment.receivedMillimes > 0) {
      this.emitChangeDue({
        kioskId,
        paymentId: payment.id,
        amountMillimes: payment.receivedMillimes,
        reason: 'REFUND',
      });
    }
  }

  private view(
    jobId: string,
    jobStatus: JobStatus,
    payment: Payment,
    expiresAt: Date,
  ): CoinSessionView {
    return {
      jobId,
      amountDueMillimes: payment.amountMillimes,
      receivedMillimes: payment.receivedMillimes,
      expiresAt: expiresAt.toISOString(),
      jobStatus,
      changeDueMillimes: payment.changeDueMillimes,
    };
  }

  private emitSession(event: CoinSessionUpdatedEvent): void {
    this.events.emit(DomainEvent.COIN_SESSION_UPDATED, event);
  }

  private emitChangeDue(event: CoinChangeDueEvent): void {
    this.events.emit(DomainEvent.COIN_CHANGE_DUE, event);
  }
}
